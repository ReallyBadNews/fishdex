import { build } from "esbuild";
import { readFileSync, writeFileSync, readdirSync } from "node:fs";
const result = await build({
  entryPoints: ["scripts/viewer.js"],
  bundle: true,
  write: false,
  minify: true,
  format: "iife",
  target: "es2020",
  legalComments: "inline",
});
writeFileSync(
  "src/generated/viewer.ts",
  `// Generated by scripts/bundle-models.mjs\nexport const viewerScript = ${JSON.stringify(result.outputFiles[0].text)};\n`,
);
const models = Object.fromEntries(
  readdirSync("assets/models")
    .filter((f) => f.endsWith(".glb"))
    .map((f) => [
      f.slice(0, -4),
      readFileSync("assets/models/" + f).toString("base64"),
    ]),
);
writeFileSync(
  "src/generated/models.ts",
  `// Original Blender assets, bundled for offline use.\nexport const models: Record<string,string> = ${JSON.stringify(models)};\n`,
);
console.log("Bundled", Object.keys(models).length, "offline models.");
